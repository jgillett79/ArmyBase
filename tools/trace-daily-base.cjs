// Brief 09 per-soldier routine trace, for comparing what is seen on the map
// with the schedule: for every soldier and every window,
//   scheduled task -> station or queue (and when) -> use start/end -> result.
//
//   node tools/trace-daily-base.cjs [soldiers=4] [out.md] [--setup "<js>"]
//
// Same base as tests/routine.cjs (starter facilities + range, weights and
// rec room; clock starts 21:30 on day 0), one full game day at 1x in 0.1 s
// ticks. Writes markdown (stdout when no file is given).
const fs = require('node:fs');
const { loadGame } = require('../tests/lib/sandbox.cjs');

const args = process.argv.slice(2);
const setupIndex = args.indexOf('--setup');
const setup = setupIndex >= 0 ? args[setupIndex + 1] : '';
const plain = setupIndex < 0 ? args : args.filter((a, i) => i !== setupIndex && i !== setupIndex + 1);
const n = Number(plain[0]) || 4;
const out = plain[1];

const g = loadGame({ seed: 3 });
g.run(`var state = new GameState(); state.cash = 5000; state.food = 300;
  state.shootingRange.level = 1; state.weightRoom.level = 1; state.recRoom.level = 1;
  state.chapter.done = true; state.chapter.introDispatched = true; state.chapter.dismissed = true;
  state.gameClockMs = 21.5 * 3600000; ${setup}
  const names = ['Grace Okafor', 'Kenji Rossi', 'Omar Chen', 'Aisha Novak', 'Lena Park', 'Tomas Reyes', 'Ivo Brandt', 'Mara Silva'];
  for (let i = 0; i < ${n}; i++) { const p = worldNodePosition('t4'); const u = new Unit({ x: p.x + i * 4, y: p.y, isCivilian: false }); u.name = names[i]; state.units.push(u); }
  state.assignBeds(); for (const u of state.units) state.rejoinRoutine(u);`);
g.advance(1200 + 30, 0.1);

const events = g.run(`state.activityLog.map(e => ({ t: formatGameMinute(e.clock / 60000), unit: e.name, event: e.event, window: e.window || null,
  station: e.station || null, group: e.group || null, reason: e.reason || null, position: e.position || null, partial: e.partial }))`);
const summary = g.run('state.dailySummary(1)');
const lines = [`# Daily routine trace — ${n} soldiers, day 2 of the base (game day 1)`, '',
  `Generated by \`node tools/trace-daily-base.cjs ${n}${setup ? ` --setup "${setup}"` : ''}\`. Each row: window → what the soldier did, with game times. ✓ completed, ½ partial, ✗ missed (reason).`, '',
  '## Day summary', '', ...summary.lines.map(l => `- ${l.text}`), summary.advice ? `- **Suggested:** ${summary.advice}` : '', ''];
const short = id => (id || '').split(':').pop();
for (const name of [...new Set(events.map(e => e.unit))]) {
  lines.push(`## ${name}`, '', '| Window | Chain | Result |', '|---|---|---|');
  let current = null, chain = [], result = '';
  const flush = () => { if (current && current.startsWith('1:')) lines.push(`| ${current.split(':')[1]} | ${chain.join(' → ') || '—'} | ${result} |`); chain = []; result = ''; };
  for (const e of events.filter(x => x.unit === name)) {
    if (e.event === 'window') { flush(); current = e.window; continue; }
    if (['completed', 'partial', 'missed', 'excluded'].includes(e.event) && e.window === current) {
      result = { completed: '✓', partial: '½', missed: '✗', excluded: '–' }[e.event] + (e.reason ? ` ${e.reason}` : '');
    }
    if (e.event === 'queue') chain.push(`${e.t} queue ${short(e.group)} #${e.position}`);
    else if (e.event === 'admitted_from_queue') chain.push(`${e.t} called`);
    else if (e.event === 'served') chain.push(`${e.t} served (1 food)`);
    else if (e.event === 'use_start') chain.push(`${e.t} ${short(e.station)}`);
    else if (e.event === 'use_end') chain.push(`${e.t} done${e.partial ? ' (cut short)' : ''}`);
    else if (e.event === 'muster') chain.push(`${e.t} parade ground (${e.reason})`);
    else if (e.event === 'grace') chain.push(`${e.t} finishing in grace`);
  }
  flush();
  lines.push('');
}
const md = lines.join('\n');
if (out) { fs.writeFileSync(out, md); console.log(`wrote ${out}`); } else console.log(md);
